onAuthStateChanged(auth, async user => {
	// Logged in
	if (user) {
		currentUser = await internalUserToUser(
			(
				await getDocs(query(collection(db, "users"), where("id", "==", user.uid)))
			).docs[0].data() as User,
		);
		resolveUser(currentUser);
	}

	// logged out
	else {
	}
});

