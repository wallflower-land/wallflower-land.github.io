export async function searchUsers(searchTerm: string): Promise<User[]> {
	if (searchTerm === "") return Promise.resolve([]);
	if (searchTerm.startsWith("@")) {
		const docs = (
			await getDocs(
				query(collection(db, "users"), where("username", "==", searchTerm.substring(1))),
			)
		).docs;
		return docs.length > 0 ? [docs[0].data() as User] : [];
	}
	return fuzzyQuery(searchTerm, "displayName", "users");
}

export const defaultPreferences = {
	darkMode: true,
	uiScale: 1,
} as const satisfies Preferences;

type Preferences = {
	darkMode: boolean;
	uiScale: number;
};

export type Preference = keyof Preferences;
export type PreferenceValue<T extends Preference> = Preferences[T];

export function getPreference<Name extends Preference>(name: Name): PreferenceValue<Name> {
	if (user()) return user()![name];

	const fromStorage = localStorage.getItem(`preference-${name}`);
	if (fromStorage) return JSON.parse(fromStorage);

	const preference = defaultPreferences[name];
	localStorage.setItem(`preference-${name}`, JSON.stringify(preference));

	return preference;
}

export async function setPreference<Name extends Preference>(
	name: Name,
	value: PreferenceValue<Name>,
): Promise<void> {
	localStorage.setItem(`preference-${name}`, JSON.stringify(value));
	if (user()) await updateUser({ [name]: value });
}

export async function getMentions(): Promise<Post[]> {
	const username = user()!.username;
	const allPosts = (
		await getDocs(query(collection(db, "posts"), orderBy("timestamp", "desc")))
	).docs.map(doc => doc.data() as Post);
	const mentions = allPosts.filter(post => new RegExp(`@${username}\\b`).test(post.body));
	return mentions;
}

export async function getRepliesToUser(user: User): Promise<Post[]> {
	const allPosts = (
		await getDocs(
			query(
				collection(db, "posts"),
				where("type", "==", "reply"),
				orderBy("timestamp", "desc"),
			),
		)
	).docs.map(doc => doc.data() as Post);

	const repliesToUser = allPosts.filter(async post => {
		const parent = (await getPostFromId(post.parent))!;
		return parent.poster === user.id;
	});

	return repliesToUser;
}

